.palette_types <- c("categorical", "sequential", "diverging")

.match_palette_type <- function(type, allow_all = TRUE) {
  choices <- if (allow_all) c("all", .palette_types) else .palette_types
  match.arg(type, choices)
}

.validate_palette_name <- function(name) {
  if (!is.character(name) || length(name) != 1L || is.na(name) ||
      !name %in% names(.ggpalettes)) {
    stop(
      sprintf(
        "`name` must be one of: %s.",
        paste(names(.ggpalettes), collapse = ", ")
      ),
      call. = FALSE
    )
  }
  name
}

.validate_alpha <- function(alpha) {
  if (!is.numeric(alpha) || length(alpha) != 1L || is.na(alpha) ||
      !is.finite(alpha) || alpha < 0 || alpha > 1) {
    stop("`alpha` must be a finite number between 0 and 1.", call. = FALSE)
  }
  alpha
}

.validate_direction <- function(direction) {
  if (!is.numeric(direction) || length(direction) != 1L ||
      is.na(direction) || !direction %in% c(-1, 1)) {
    stop("`direction` must be either 1 or -1.", call. = FALSE)
  }
  direction
}

#' List available ggpalettes palettes
#'
#' @param type Palette type: all, categorical, sequential, or diverging.
#' @return A character vector containing the available palette names.
#' @export
#' @examples
#' gg_palette_names()
#' gg_palette_names("diverging")
gg_palette_names <- function(type = c("all", .palette_types)) {
  type <- .match_palette_type(type)
  if (type == "all") {
    return(names(.ggpalettes))
  }
  names(.ggpalettes)[vapply(
    .ggpalettes,
    function(palette) identical(palette$type, type),
    logical(1)
  )]
}

#' Inspect the ggpalettes catalogue
#'
#' @param name Optional palette name or vector of names.
#' @param type Palette type used when `name` is `NULL`.
#' @return A data frame describing palette names, types, sizes, and purposes.
#' @export
#' @examples
#' gg_palette_info()
#' gg_palette_info(type = "categorical")
#' gg_palette_info("meadow")
gg_palette_info <- function(name = NULL,
                            type = c("all", .palette_types)) {
  if (is.null(name)) {
    selected <- gg_palette_names(type)
  } else {
    if (!is.character(name) || !length(name) || anyNA(name)) {
      stop("`name` must be `NULL` or a character vector.", call. = FALSE)
    }
    unknown <- setdiff(name, names(.ggpalettes))
    if (length(unknown)) {
      stop(
        sprintf("Unknown palette name(s): %s.", paste(unknown, collapse = ", ")),
        call. = FALSE
      )
    }
    selected <- unique(name)
  }
  data.frame(
    name = selected,
    type = vapply(selected, function(item) .ggpalettes[[item]]$type,
                  character(1)),
    colours = vapply(selected, function(item) {
      length(.ggpalettes[[item]]$colours)
    }, integer(1)),
    description = vapply(selected, function(item) {
      .ggpalettes[[item]]$description
    }, character(1)),
    stringsAsFactors = FALSE,
    row.names = NULL
  )
}

#' Retrieve a curated colour palette
#'
#' @param name Palette name. See [gg_palette_names()].
#' @param n Number of colours to return. When `NULL`, returns the original
#'   anchors. Larger values are interpolated.
#' @param direction Palette direction: `1` for the original order or `-1` for
#'   the reversed order.
#' @param alpha Opacity between 0 and 1.
#' @param space Colour space used for interpolation: Lab or rgb.
#'
#' @return A character vector of hexadecimal colour values.
#' @export
#' @examples
#' gg_palette("meadow")
#' gg_palette("ocean", n = 10)
#' gg_palette("ember", direction = -1, alpha = 0.8)
gg_palette <- function(name = "meadow", n = NULL, direction = 1,
                       alpha = 1, space = c("Lab", "rgb")) {
  name <- .validate_palette_name(name)
  direction <- .validate_direction(direction)
  alpha <- .validate_alpha(alpha)
  space <- match.arg(space)
  colours <- .ggpalettes[[name]]$colours
  if (direction == -1) {
    colours <- rev(colours)
  }
  if (!is.null(n)) {
    if (!is.numeric(n) || length(n) != 1L || is.na(n) ||
        !is.finite(n) || n < 1 || n != as.integer(n)) {
      stop("`n` must be a positive whole number or `NULL`.", call. = FALSE)
    }
    n <- as.integer(n)
    if (n <= length(colours)) {
      colours <- colours[seq_len(n)]
    } else {
      colours <- grDevices::colorRampPalette(colours, space = space)(n)
    }
  }
  if (alpha < 1) {
    colours <- grDevices::adjustcolor(colours, alpha.f = alpha)
  }
  unname(colours)
}

#' Create a palette function
#'
#' This follows the palette-function pattern used by scientific palette
#' packages: the returned function accepts the number of colours needed.
#'
#' @param name Palette name.
#' @param alpha Opacity between 0 and 1.
#' @param reverse Reverse the palette.
#' @param space Interpolation colour space.
#' @return A function with one argument, `n`.
#' @export
#' @examples
#' pal <- pal_ggpalette("atelier")
#' pal(6)
pal_ggpalette <- function(name = "meadow", alpha = 1, reverse = FALSE,
                          space = c("Lab", "rgb")) {
  name <- .validate_palette_name(name)
  alpha <- .validate_alpha(alpha)
  if (!is.logical(reverse) || length(reverse) != 1L || is.na(reverse)) {
    stop("`reverse` must be TRUE or FALSE.", call. = FALSE)
  }
  space <- match.arg(space)
  force(name)
  force(alpha)
  force(reverse)
  force(space)
  function(n) {
    gg_palette(
      name,
      n = n,
      direction = if (reverse) -1 else 1,
      alpha = alpha,
      space = space
    )
  }
}

.scale_ggpalette <- function(aesthetics, name, discrete, binned, alpha,
                             direction, space, ...) {
  name <- .validate_palette_name(name)
  alpha <- .validate_alpha(alpha)
  direction <- .validate_direction(direction)
  space <- match.arg(space, c("Lab", "rgb"))
  if (is.null(discrete)) {
    discrete <- identical(.ggpalettes[[name]]$type, "categorical")
  }
  if (!is.logical(discrete) || length(discrete) != 1L || is.na(discrete)) {
    stop("`discrete` must be TRUE, FALSE, or NULL.", call. = FALSE)
  }
  if (!is.logical(binned) || length(binned) != 1L || is.na(binned)) {
    stop("`binned` must be TRUE or FALSE.", call. = FALSE)
  }
  if (isTRUE(discrete) && isTRUE(binned)) {
    stop("`binned` cannot be TRUE for a discrete scale.", call. = FALSE)
  }
  palette <- pal_ggpalette(
    name,
    alpha = alpha,
    reverse = direction == -1,
    space = space
  )
  if (isTRUE(discrete)) {
    return(ggplot2::discrete_scale(
      aesthetics = aesthetics,
      palette = palette,
      ...
    ))
  }
  colours <- palette(256L)
  if (isTRUE(binned)) {
    if (identical(aesthetics, "colour")) {
      return(ggplot2::scale_colour_stepsn(colours = colours, ...))
    }
    return(ggplot2::scale_fill_stepsn(colours = colours, ...))
  }
  if (identical(aesthetics, "colour")) {
    ggplot2::scale_colour_gradientn(colours = colours, ...)
  } else {
    ggplot2::scale_fill_gradientn(colours = colours, ...)
  }
}

#' ggplot2 colour and fill scales using ggpalettes
#'
#' When `discrete` is `NULL`, categorical palettes use a discrete scale and
#' sequential/diverging palettes use a continuous gradient.
#'
#' @param name Palette name.
#' @param discrete Use a discrete scale. `NULL` selects from palette type.
#' @param binned Use a binned continuous scale.
#' @param alpha Opacity between 0 and 1.
#' @param direction Palette direction: 1 or -1.
#' @param space Interpolation colour space.
#' @param ... Additional arguments passed to the ggplot2 scale.
#' @return A ggplot2 scale object.
#' @export
#' @examples
#' library(ggplot2)
#' ggplot(iris, aes(Sepal.Length, Sepal.Width, colour = Species)) +
#'   geom_point(size = 2) +
#'   scale_colour_ggpalette("meadow")
scale_colour_ggpalette <- function(name = "meadow", discrete = NULL,
                                   binned = FALSE, alpha = 1,
                                   direction = 1,
                                   space = c("Lab", "rgb"), ...) {
  .scale_ggpalette(
    "colour", name, discrete, binned, alpha, direction, space, ...
  )
}

#' @rdname scale_colour_ggpalette
#' @export
scale_color_ggpalette <- scale_colour_ggpalette

#' @rdname scale_colour_ggpalette
#' @export
scale_fill_ggpalette <- function(name = "meadow", discrete = NULL,
                                 binned = FALSE, alpha = 1,
                                 direction = 1,
                                 space = c("Lab", "rgb"), ...) {
  .scale_ggpalette(
    "fill", name, discrete, binned, alpha, direction, space, ...
  )
}
